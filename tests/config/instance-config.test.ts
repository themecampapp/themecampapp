import { mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { experimental_readRawConfig } from "wrangler";
import { validateConfig } from "../../config/schema";
import { readConfig, writeWrangler } from "../../scripts/config-to-wrangler";

// Open-source plan, Units 2.1 and 2.2: instance settings live in config/*.json, and the
// Wrangler configs are generated from them (and gitignored). Before the switch, a test proved
// hosted + staging reproduced the hand-written files exactly, apart from the staging mail
// allowlist, which is a staging Worker secret. The hosted configs' policies are checked in
// camp-worker.test.ts and platform-worker.test.ts.

const read = (path: string) =>
  experimental_readRawConfig({ config: path }).rawConfig as Record<string, unknown>;

const out = mkdtempSync(join(tmpdir(), "tca-wrangler-"));
afterAll(() => rmSync(out, { recursive: true, force: true }));
writeWrangler(out, [readConfig("hosted"), readConfig("staging")]);

describe("instance configs", () => {
  it.each(readdirSync("config").filter((f) => f.endsWith(".json")))("%s is valid", (file) => {
    expect(() =>
      validateConfig(JSON.parse(readFileSync(join("config", file), "utf8")), file),
    ).not.toThrow();
  });

  it("name every problem: a missing field, a wrong value, a setting that doesn't exist", () => {
    const good = readConfig("example") as unknown as Record<string, unknown>;
    const bad = structuredClone(good) as Record<string, Record<string, unknown>>;
    delete bad.domain;
    bad.mail.provider = "carrier pigeon";
    bad.features.signupPage = "yes";
    (bad as Record<string, unknown>).secretKey = "sk_live_123";
    let message = "";
    try {
      validateConfig(bad, "bad.json");
    } catch (e) {
      message = (e as Error).message;
    }
    expect(message).toContain("domain is missing");
    expect(message).toContain("mail.provider must be one of plunk, postmark");
    expect(message).toContain("features.signupPage must be true or false");
    expect(message).toContain("secretKey isn't a setting");
  });

  it("never hold the staging allowlist or anything secret-looking", () => {
    for (const file of readdirSync("config").filter((f) => f.endsWith(".json"))) {
      const text = readFileSync(join("config", file), "utf8");
      expect(text, file).not.toMatch(/MAIL_ALLOWLIST|sk_|secret_|@gmail\.com|postgres:\/\//i);
    }
  });
});

describe("the generated Wrangler configs", () => {
  it("are written for both Workers, marked as generated", () => {
    for (const file of ["wrangler.jsonc", "platform/wrangler.jsonc"]) {
      const text = readFileSync(join(out, file), "utf8");
      expect(text.startsWith("// Generated by scripts/config-to-wrangler.ts")).toBe(true);
      expect(read(join(out, file)).env).toHaveProperty("staging");
    }
  });

  it("are gitignored, so only config/*.json is ever edited", () => {
    const ignore = readFileSync(".gitignore", "utf8");
    expect(ignore).toContain("/wrangler.jsonc");
    expect(ignore).toContain("/platform/wrangler.jsonc");
  });
});
